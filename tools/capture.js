#!/usr/bin/env node
/* ==========================================================================
   tools/capture.js — one-time offline step: full-page screenshots of every
   live project, saved to assets/screens/<slug>.png (+ .webp if `sharp` is
   installed), then js/screens.js is regenerated so the site uses them.

   Usage (from the repo root):
     cd tools && npm install          # installs playwright (+ optional sharp)
     npx playwright install chromium  # first time only
     node capture.js                  # all projects in projects.json
     node capture.js talk-to-trader   # only the given slug(s)

   The website itself stays pure HTML/CSS/JS — this script is never shipped.
   ========================================================================== */
const fs = require("fs");
const path = require("path");
const { chromium } = require("playwright");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "assets", "screens");
const MANIFEST = path.join(ROOT, "js", "screens.js");
const WIDTH = 1440;
const MAX_HEIGHT = 9000; // very long pages are clipped to keep files small

const only = process.argv.slice(2);
const LIST = process.env.PROJECTS_JSON || path.join(__dirname, "projects.json"); // override for testing
const projects = JSON.parse(fs.readFileSync(LIST, "utf8")).filter(
  (p) => !only.length || only.includes(p.slug)
);

let sharp = null;
try {
  sharp = require("sharp");
} catch (e) {
  console.log("ℹ sharp not installed — saving PNG only (npm i sharp for WebP).");
}

/** Read the current manifest so captures merge instead of overwrite */
function readManifest() {
  if (!fs.existsSync(MANIFEST)) return {};
  const src = fs.readFileSync(MANIFEST, "utf8");
  const m = src.match(/window\.LOCAL_SCREENS\s*=\s*(\{[\s\S]*?\});/);
  try {
    return m ? JSON.parse(m[1]) : {};
  } catch (e) {
    return {};
  }
}

function writeManifest(map) {
  const body = JSON.stringify(map, null, 2);
  fs.writeFileSync(
    MANIFEST,
    `/* AUTO-GENERATED by tools/capture.js — you can also edit it by hand.
   Maps a project slug to its local full-page screenshot. Projects missing
   here fall back to a live screenshot service, then to a placeholder. */
window.LOCAL_SCREENS = ${body};
`
  );
}

/** Scroll to the bottom so lazy images / reveal animations render */
async function autoScroll(page) {
  await page.evaluate(async () => {
    await new Promise((resolve) => {
      let y = 0;
      const step = () => {
        window.scrollBy(0, 600);
        y += 600;
        if (y < document.body.scrollHeight && y < 20000) setTimeout(step, 120);
        else resolve();
      };
      step();
    });
    window.scrollTo(0, 0);
  });
}

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const manifest = readManifest();
  const browser = await chromium.launch();
  const context = await browser.newContext({
    viewport: { width: WIDTH, height: 900 },
    deviceScaleFactor: 1,
    colorScheme: "light",
    userAgent:
      "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36",
  });

  for (const p of projects) {
    const page = await context.newPage();
    process.stdout.write(`→ ${p.slug.padEnd(22)} ${p.url} … `);
    try {
      await page.goto(p.url, { waitUntil: "networkidle", timeout: 45000 }).catch(() => page.waitForTimeout(3000));
      await autoScroll(page);
      await page.waitForTimeout(1500);
      // kill fixed headers/animations duplicating down the page
      await page.addStyleTag({ content: "*{animation:none!important;transition:none!important;scroll-behavior:auto!important}" });
      const height = await page.evaluate(() => document.documentElement.scrollHeight);
      const png = path.join(OUT, `${p.slug}.png`);
      await page.screenshot({ path: png, fullPage: true, clip: { x: 0, y: 0, width: WIDTH, height: Math.min(height, MAX_HEIGHT) } });
      let rel = `assets/screens/${p.slug}.png`;
      if (sharp) {
        const webp = path.join(OUT, `${p.slug}.webp`);
        await sharp(png).webp({ quality: 78 }).toFile(webp);
        fs.unlinkSync(png);
        rel = `assets/screens/${p.slug}.webp`;
      }
      manifest[p.slug] = rel;
      console.log(`✔ ${Math.min(height, MAX_HEIGHT)}px → ${rel}`);
    } catch (err) {
      console.log(`✖ ${err.message.split("\n")[0]}`);
    } finally {
      await page.close();
    }
  }

  await browser.close();
  writeManifest(manifest);
  console.log(`\nUpdated ${path.relative(ROOT, MANIFEST)} (${Object.keys(manifest).length} screenshots).`);
})();
