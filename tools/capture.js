#!/usr/bin/env node
/* ==========================================================================
   tools/capture.js — one-time offline step: full-page screenshots of every
   live project, saved to assets/screens/<slug>.png (+ .webp if `sharp` is
   installed), then js/screens.js is regenerated so the site uses them.

   Usage (from the repo root):
     cd tools && npm install          # installs playwright (+ optional sharp)
     npx playwright install chromium  # first time only
     node capture.js                  # all projects in projects.json
     node capture.js talk-to-trader   # only the given slug(s)

   The website itself stays pure HTML/CSS/JS — this script is never shipped.
   ========================================================================== */
const fs = require("fs");
const path = require("path");
const { chromium } = require("playwright");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "assets", "screens");
const MANIFEST = path.join(ROOT, "js", "screens.js");
const WIDTH = 1440;
const MAX_HEIGHT = 9000; // very long pages are clipped to keep files small

const only = process.argv.slice(2);
const LIST = process.env.PROJECTS_JSON || path.join(__dirname, "projects.json"); // override for testing
const projects = JSON.parse(fs.readFileSync(LIST, "utf8")).filter(
  (p) => !only.length || only.includes(p.slug)
);

let sharp = null;
try {
  sharp = require("sharp");
} catch (e) {
  console.log("ℹ sharp not installed — saving PNG only (npm i sharp for WebP).");
}

/** Read the current manifest so captures merge instead of overwrite */
function readManifest() {
  if (!fs.existsSync(MANIFEST)) return {};
  const src = fs.readFileSync(MANIFEST, "utf8");
  const m = src.match(/window\.LOCAL_SCREENS\s*=\s*(\{[\s\S]*?\});/);
  try {
    return m ? JSON.parse(m[1]) : {};
  } catch (e) {
    return {};
  }
}

function writeManifest(map) {
  const body = JSON.stringify(map, null, 2);
  fs.writeFileSync(
    MANIFEST,
    `/* AUTO-GENERATED by tools/capture.js — you can also edit it by hand.
   Maps a project slug to its local full-page screenshot. Projects missing
   here fall back to a live screenshot service, then to a placeholder. */
window.LOCAL_SCREENS = ${body};
`
  );
}

/** Scroll to the bottom so lazy images / reveal animations render */
async function autoScroll(page) {
  // slow enough for IntersectionObserver "reveal on scroll" sections to fire
  await page.evaluate(async () => {
    await new Promise((resolve) => {
      let y = 0;
      const step = () => {
        window.scrollBy(0, 450);
        y += 450;
        if (y < document.body.scrollHeight && y < 20000) setTimeout(step, 260);
        else resolve();
      };
      step();
    });
  });
  await page.waitForTimeout(900);
  await page.evaluate(() => window.scrollTo(0, 0));
}

/** Wait out bot-checks / preloaders ("Please wait…", "Checking your browser…") */
async function waitPastInterstitial(page, ms = 25000) {
  const re = /please wait while your request is being verified|checking your browser|just a moment/i;
  const end = Date.now() + ms;
  while (Date.now() < end) {
    const text = await page.evaluate(() => (document.body ? document.body.innerText.slice(0, 2000) : "")).catch(() => "");
    if (!re.test(text)) return true;
    await page.waitForTimeout(1500);
  }
  return false;
}

/** Click a typical cookie-consent "accept" button if one is showing */
async function dismissCookies(page) {
  const labels = /^(accept( all)?( cookies)?|allow( all)?( cookies)?|i agree|agree|got it|ok(ay)?|accept & close)$/i;
  for (const frame of page.frames()) {
    const buttons = await frame.$$("button, a[role=button], [role=button], input[type=button], input[type=submit]").catch(() => []);
    for (const b of buttons) {
      const t = ((await b.innerText().catch(() => "")) || (await b.getAttribute("value").catch(() => "")) || "").trim();
      if (labels.test(t) && (await b.isVisible().catch(() => false))) {
        await b.click({ timeout: 2000 }).catch(() => {});
        await page.waitForTimeout(600);
        return true;
      }
    }
  }
  return false;
}

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const manifest = readManifest();
  const browser = await chromium.launch();
  const context = await browser.newContext({
    viewport: { width: WIDTH, height: 900 },
    deviceScaleFactor: 1,
    colorScheme: "light",
    userAgent:
      "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36",
  });

  for (const p of projects) {
    const page = await context.newPage();
    // "capture" lets the screenshot come from another page (e.g. staging)
    // while the site keeps showing the public "url"
    const target = p.capture || p.url;
    process.stdout.write(`→ ${p.slug.padEnd(22)} ${target} … `);
    try {
      await page.goto(target, { waitUntil: "networkidle", timeout: 45000 }).catch(() => page.waitForTimeout(3000));
      if (!(await waitPastInterstitial(page))) process.stdout.write("(still on a verification page) ");
      await page.waitForLoadState("networkidle", { timeout: 15000 }).catch(() => {});
      // preloaders / intro animations: per-project override via "wait" in projects.json
      await page.waitForTimeout(p.wait || 3000);
      await dismissCookies(page);
      await autoScroll(page);
      await page.waitForTimeout(1500);
      // "forceReveal": true in projects.json → un-hide scroll-reveal blocks that
      // stay at opacity:0 in headless browsers (AOS/WOW/custom reveal scripts)
      if (p.forceReveal) {
        await page.evaluate(() => {
          document.querySelectorAll("body *").forEach((el) => {
            const s = getComputedStyle(el);
            if (s.position === "fixed" || el.offsetHeight < 20) return;
            // leave menus / dropdowns / modals closed
            if (el.closest("header, nav, [role=menu], [role=dialog]")) return;
            if (s.opacity === "0" || s.visibility === "hidden") {
              el.style.setProperty("opacity", "1", "important");
              el.style.setProperty("visibility", "visible", "important");
              el.style.setProperty("transform", "none", "important");
            }
          });
        });
        await page.waitForTimeout(800);
      }
      // note: CSS animations are NOT disabled — fade-in sections with fill-mode
      // "forwards" would snap back to opacity:0 and render blank.
      const height = await page.evaluate(() => document.documentElement.scrollHeight);
      const png = path.join(OUT, `${p.slug}.png`);
      await page.screenshot({ path: png, fullPage: true, clip: { x: 0, y: 0, width: WIDTH, height: Math.min(height, MAX_HEIGHT) } });
      let rel = `assets/screens/${p.slug}.png`;
      if (sharp) {
        const webp = path.join(OUT, `${p.slug}.webp`);
        await sharp(png).webp({ quality: 78 }).toFile(webp);
        // light 800px variant used by cards + showcase (the site falls back to
        // the full image if this file is missing)
        await sharp(png).resize({ width: 800 }).webp({ quality: 72 }).toFile(path.join(OUT, `${p.slug}-sm.webp`));
        fs.unlinkSync(png);
        rel = `assets/screens/${p.slug}.webp`;
      }
      manifest[p.slug] = rel;
      console.log(`✔ ${Math.min(height, MAX_HEIGHT)}px → ${rel}`);
    } catch (err) {
      console.log(`✖ ${err.message.split("\n")[0]}`);
    } finally {
      await page.close();
    }
  }

  await browser.close();
  writeManifest(manifest);
  console.log(`\nUpdated ${path.relative(ROOT, MANIFEST)} (${Object.keys(manifest).length} screenshots).`);
})();
